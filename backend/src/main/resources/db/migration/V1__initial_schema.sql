CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_address VARCHAR(42) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE auth_nonces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nonce VARCHAR(64) NOT NULL UNIQUE,
    wallet_address VARCHAR(42) NOT NULL,
    chain_id BIGINT NOT NULL,
    siwe_message TEXT NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE NULL
);

CREATE INDEX idx_auth_nonces_wallet_expires ON auth_nonces (wallet_address, expires_at);

CREATE TABLE deals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id VARCHAR(66) NOT NULL UNIQUE,
    chain_id BIGINT NOT NULL,
    contract_address VARCHAR(42) NOT NULL,
    seller_address VARCHAR(42) NOT NULL,
    buyer_address VARCHAR(42) NULL,
    arbiter_address VARCHAR(42) NOT NULL,
    amount_wei VARCHAR(78) NOT NULL,
    terms_hash VARCHAR(66) NOT NULL,
    funding_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    delivery_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    inspection_window_seconds BIGINT NOT NULL,
    delivered_at TIMESTAMP WITH TIME ZONE NULL,
    funded_at TIMESTAMP WITH TIME ZONE NULL,
    status VARCHAR(24) NOT NULL,
    on_chain_bound BOOLEAN NOT NULL DEFAULT FALSE,
    settled BOOLEAN NOT NULL DEFAULT FALSE,
    create_tx_hash VARCHAR(66) NULL UNIQUE,
    buyer_award_wei VARCHAR(78) NULL,
    seller_award_wei VARCHAR(78) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_deals_status CHECK (
        status IN ('DRAFT', 'CREATED', 'FUNDED', 'DELIVERED', 'RELEASED', 'REFUNDED', 'DISPUTED', 'RESOLVED', 'CANCELLED')
    ),
    CONSTRAINT chk_deals_distinct_roles CHECK (
        seller_address <> arbiter_address
    )
);

CREATE INDEX idx_deals_seller ON deals (seller_address);
CREATE INDEX idx_deals_buyer ON deals (buyer_address);
CREATE INDEX idx_deals_arbiter ON deals (arbiter_address);
CREATE INDEX idx_deals_status ON deals (status);

CREATE TABLE deal_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deal_id BIGINT NOT NULL UNIQUE REFERENCES deals(id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    terms_text TEXT NOT NULL,
    canonical_json TEXT NOT NULL,
    terms_hash VARCHAR(66) NOT NULL,
    schema_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE deal_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id VARCHAR(66) NOT NULL,
    event_type VARCHAR(48) NOT NULL,
    actor_address VARCHAR(42) NULL,
    tx_hash VARCHAR(66) NULL,
    block_number BIGINT NULL,
    log_index INT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX uq_deal_events_tx_log ON deal_events (tx_hash, log_index);
CREATE INDEX idx_deal_events_trade_id ON deal_events (trade_id);

CREATE TABLE chain_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_hash VARCHAR(66) NOT NULL,
    log_index INT NOT NULL,
    block_number BIGINT NOT NULL,
    block_timestamp BIGINT NOT NULL,
    contract_address VARCHAR(42) NOT NULL,
    event_type VARCHAR(48) NOT NULL,
    trade_id VARCHAR(66) NOT NULL,
    actor_address VARCHAR(42) NULL,
    amount_wei VARCHAR(78) NULL,
    buyer_award_wei VARCHAR(78) NULL,
    seller_award_wei VARCHAR(78) NULL,
    terms_hash VARCHAR(66) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_chain_events_tx_log UNIQUE (tx_hash, log_index)
);

CREATE INDEX idx_chain_events_trade_id ON chain_events (trade_id);
CREATE INDEX idx_chain_events_block ON chain_events (block_number);

CREATE TABLE blockchain_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id VARCHAR(66) NOT NULL,
    tx_hash VARCHAR(66) NOT NULL UNIQUE,
    operation VARCHAR(48) NOT NULL,
    status VARCHAR(24) NOT NULL,
    block_number BIGINT NULL,
    submitted_by VARCHAR(42) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE NULL
);

CREATE INDEX idx_blockchain_tx_trade_id ON blockchain_transactions (trade_id);

CREATE TABLE disputes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id VARCHAR(66) NOT NULL UNIQUE,
    opened_by VARCHAR(42) NOT NULL,
    reason VARCHAR(200) NOT NULL,
    summary TEXT NOT NULL,
    status VARCHAR(24) NOT NULL,
    buyer_award_wei VARCHAR(78) NULL,
    seller_award_wei VARCHAR(78) NULL,
    resolution_rationale TEXT NULL,
    open_tx_hash VARCHAR(66) NULL,
    resolve_tx_hash VARCHAR(66) NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT chk_disputes_status CHECK (status IN ('OPEN', 'RESOLVED'))
);

CREATE INDEX idx_disputes_trade_id ON disputes (trade_id);

CREATE TABLE dispute_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id BIGINT NOT NULL REFERENCES disputes(id) ON DELETE CASCADE,
    submitted_by VARCHAR(42) NOT NULL,
    title VARCHAR(160) NOT NULL,
    notes TEXT NOT NULL,
    file_name VARCHAR(255) NULL,
    mime_type VARCHAR(120) NULL,
    size_bytes BIGINT NULL,
    sha256_hex VARCHAR(64) NULL,
    storage_key VARCHAR(255) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_dispute_evidence_dispute_id ON dispute_evidence (dispute_id);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(64) NOT NULL,
    actor_address VARCHAR(42) NULL,
    resource_type VARCHAR(48) NOT NULL,
    resource_id VARCHAR(80) NOT NULL,
    correlation_id VARCHAR(64) NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_logs_resource ON audit_logs (resource_type, resource_id);

CREATE TABLE chain_sync_state (
    id INT PRIMARY KEY,
    chain_id BIGINT NOT NULL,
    contract_address VARCHAR(42) NOT NULL,
    last_synced_block BIGINT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
