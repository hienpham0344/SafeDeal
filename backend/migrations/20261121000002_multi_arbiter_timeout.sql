ALTER TABLE disputes
    ADD COLUMN disputed_at TIMESTAMP WITH TIME ZONE NULL,
    ADD COLUMN dispute_timeout_seconds BIGINT NOT NULL DEFAULT 1209600;

CREATE TABLE dispute_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id BIGINT NOT NULL REFERENCES disputes(id) ON DELETE CASCADE,
    trade_id VARCHAR(66) NOT NULL,
    voter_address VARCHAR(42) NOT NULL,
    voter_role VARCHAR(16) NOT NULL CHECK (voter_role IN ('BUYER', 'SELLER', 'ARBITER')),
    buyer_award_wei VARCHAR(78) NOT NULL,
    seller_award_wei VARCHAR(78) NOT NULL,
    proposal_hash VARCHAR(66) NOT NULL,
    rationale TEXT NULL,
    tx_hash VARCHAR(66) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_dispute_votes_dispute_voter UNIQUE (dispute_id, voter_address)
);

CREATE INDEX idx_dispute_votes_trade_id ON dispute_votes (trade_id);
